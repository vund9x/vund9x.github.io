/**
 * Safely retrieve a property from an object, preventing Prototype Pollution.
 * @param {Object} obj The source object.
 * @param {string|number} key The property key.
 * @returns {*} The property value, or undefined if not found or unsafe.
 */
function getSafeProperty(obj, key) {
    if (!obj || typeof obj !== 'object') return undefined;
    const keyStr = String(key);
    if (keyStr === '__proto__' || keyStr === 'constructor' || keyStr === 'prototype') {
        return undefined;
    }
    return Object.prototype.hasOwnProperty.call(obj, keyStr) ? Reflect.get(obj, keyStr) : undefined;
}

