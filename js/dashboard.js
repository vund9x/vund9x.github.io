// Initialize particles based on weather type
function initParticles() {
    particles = [];
    let count = 0;
    if (weatherType === 'rainy') {
        count = Math.floor((width * height) / 12000);
        count = Math.min(count, 120);
        for (let i = 0; i < count; i++) {
            particles.push({
                x: Math.random() * width,
                y: Math.random() * height - height,
                length: Math.random() * 20 + 20,
                speed: Math.random() * 8 + 10,
                opacity: Math.random() * 0.25 + 0.1,
                lineWidth: Math.random() * 1 + 0.5
            });
        }
    } else if (weatherType === 'snowy') {
        count = Math.floor((width * height) / 22000);
        count = Math.min(count, 70);
        for (let i = 0; i < count; i++) {
            particles.push({
                x: Math.random() * width,
                y: Math.random() * height,
                radius: Math.random() * 2.5 + 1,
                speed: Math.random() * 0.8 + 0.4,
                density: Math.random() * 20,
                opacity: Math.random() * 0.4 + 0.2
            });
        }
    } else if (weatherType === 'cloudy') {
        count = 8;
        for (let i = 0; i < count; i++) {
            particles.push({
                x: Math.random() * width,
                y: Math.random() * height,
                radius: Math.random() * 150 + 150,
                speed: Math.random() * 0.12 + 0.04,
                opacity: Math.random() * 0.015 + 0.005,
                angle: Math.random() * Math.PI * 2
            });
        }
    } else if (weatherType === 'default') {
        count = 25;
        for (let i = 0; i < count; i++) {
            particles.push({
                x: Math.random() * width,
                y: Math.random() * height,
                radius: Math.random() * 1.5 + 0.5,
                speed: Math.random() * 0.15 + 0.05,
                opacity: Math.random() * 0.45 + 0.1,
                fadeDirection: Math.random() > 0.5 ? 1 : -1
            });
        }
    }
}

// Main animation loop
function updateAndDraw() {
    ctx.clearRect(0, 0, width, height);

    const isLight = document.documentElement.getAttribute('data-theme') === 'light';

    if (weatherType === 'rainy') {
        particles.forEach(p => {
            ctx.beginPath();
            ctx.lineWidth = p.lineWidth;
            ctx.strokeStyle = isLight ? `rgba(37, 99, 235, ${p.opacity * 1.5})` : `rgba(186, 230, 253, ${p.opacity})`; // Darker blue in light theme
            ctx.moveTo(p.x, p.y);
            ctx.lineTo(p.x - 1.5, p.y + p.length);
            ctx.stroke();

            p.y += p.speed;
            p.x -= 1.5;

            if (p.y > height || p.x < 0) {
                p.y = -p.length;
                p.x = Math.random() * (width + 100);
                p.speed = Math.random() * 8 + 10;
            }
        });
    } else if (weatherType === 'snowy') {
        particles.forEach(p => {
            ctx.beginPath();
            ctx.fillStyle = isLight ? `rgba(71, 85, 105, ${p.opacity * 1.5})` : `rgba(255, 255, 255, ${p.opacity})`; // Slate snow in light theme
            ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            ctx.fill();

            p.y += p.speed;
            p.density += 0.01;
            p.x += Math.sin(p.density) * 0.4;

            if (p.y > height) {
                p.y = -10;
                p.x = Math.random() * width;
                p.density = Math.random() * 20;
            }
        });
    } else if (weatherType === 'cloudy') {
        particles.forEach(p => {
            let grad = ctx.createRadialGradient(p.x, p.y, 0, p.x, p.y, p.radius);
            grad.addColorStop(0, isLight ? `rgba(148, 163, 184, ${p.opacity * 1.5})` : `rgba(226, 232, 240, ${p.opacity})`);
            grad.addColorStop(1, 'rgba(255, 255, 255, 0)');
            ctx.fillStyle = grad;
            ctx.beginPath();
            ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            ctx.fill();

            p.x += p.speed;
            p.y += Math.sin(p.angle) * 0.04;
            p.angle += 0.005;

            if (p.x - p.radius > width) {
                p.x = -p.radius;
                p.y = Math.random() * height;
            }
        });
    } else if (weatherType === 'sunny') {
        const sunX = width * 0.85;
        const sunY = height * 0.15;

        ctx.save();
        ctx.translate(sunX, sunY);
        sunBeamAngle += 0.0003;
        ctx.rotate(sunBeamAngle);

        const numRays = 10;
        const maxRadius = Math.max(width, height);
        for (let i = 0; i < numRays; i++) {
            ctx.rotate((Math.PI * 2) / numRays);
            ctx.beginPath();
            ctx.moveTo(0, 0);
            const rayWidth = 0.04 + Math.sin(Date.now() * 0.0008 + i) * 0.008;
            ctx.lineTo(maxRadius, -maxRadius * rayWidth);
            ctx.lineTo(maxRadius, maxRadius * rayWidth);
            ctx.closePath();

            const grad = ctx.createLinearGradient(0, 0, maxRadius, 0);
            grad.addColorStop(0, isLight ? 'rgba(245, 158, 11, 0.04)' : 'rgba(253, 224, 71, 0.03)'); // Warm amber/yellow
            grad.addColorStop(0.5, isLight ? 'rgba(245, 158, 11, 0.01)' : 'rgba(253, 224, 71, 0.008)');
            grad.addColorStop(1, 'rgba(253, 224, 71, 0)');
            ctx.fillStyle = grad;
            ctx.fill();
        }
        ctx.restore();

        // Faint ambient halo
        ctx.beginPath();
        const flareGrad = ctx.createRadialGradient(sunX, sunY, 0, sunX, sunY, 350);
        flareGrad.addColorStop(0, isLight ? 'rgba(245, 158, 11, 0.08)' : 'rgba(253, 224, 71, 0.06)');
        flareGrad.addColorStop(0.4, isLight ? 'rgba(59, 130, 246, 0.02)' : 'rgba(56, 189, 248, 0.015)');
        flareGrad.addColorStop(1, 'rgba(0, 0, 0, 0)');
        ctx.fillStyle = flareGrad;
        ctx.arc(sunX, sunY, 350, 0, Math.PI * 2);
        ctx.fill();
    } else if (weatherType === 'default') {
        particles.forEach(p => {
            ctx.beginPath();
            ctx.fillStyle = isLight ? `rgba(59, 130, 246, ${p.opacity * 1.5})` : `rgba(255, 255, 255, ${p.opacity})`; // Blue dots in light theme
            ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            ctx.fill();

            p.opacity += 0.003 * p.fadeDirection;
            if (p.opacity > 0.55) {
                p.fadeDirection = -1;
            } else if (p.opacity < 0.05) {
                p.fadeDirection = 1;
            }

            p.y -= p.speed;
            if (p.y < 0) {
                p.y = height;
                p.x = Math.random() * width;
            }
        });
    }

    weatherAnimationId = requestAnimationFrame(updateAndDraw);
}

// Update weather type and re-initialize
function setWeatherEffect(code) {
    let newType = 'default';
    if (code === 0 || code === 1) {
        newType = 'sunny';
    } else if (code === 2 || code === 3 || code === 45 || code === 48) {
        newType = 'cloudy';
    } else if ([51, 53, 55, 61, 63, 65, 95, 96, 99].includes(code)) {
        newType = 'rainy';
    } else if ([71, 73, 75].includes(code)) {
        newType = 'snowy';
    }

    if (newType !== weatherType) {
        weatherType = newType;
        initParticles();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-button').forEach(button => {
        button.addEventListener('click', (event) => {
            setLanguage(event.target.getAttribute('data-lang'));
        });
    });
    setLanguage(currentLang); // Set initial language on load
    updateDashboardClock();
    setInterval(updateDashboardClock, 1000);

    // Start Canvas Weather Loop
    initParticles();
    updateAndDraw();

    window.addEventListener('resize', () => {
        width = weatherCanvas.width = window.innerWidth;
        height = weatherCanvas.height = window.innerHeight;
        initParticles();
    });
});

// Mapping US AQI to descriptions and colors
function getUsAqiDescription(aqi) {
    let descriptionKey = "unknown";
    let color = "text-slate-400";
    let barBg = "bg-slate-500";
    if (aqi >= 0 && aqi <= 50) { descriptionKey = "good"; color = "text-emerald-400"; barBg = "bg-emerald-500"; }
    else if (aqi <= 100) { descriptionKey = "moderate"; color = "text-amber-400"; barBg = "bg-amber-500"; }
    else if (aqi <= 150) { descriptionKey = "unhealthy_sensitive"; color = "text-orange-400"; barBg = "bg-orange-500"; }
    else if (aqi <= 200) { descriptionKey = "unhealthy"; color = "text-rose-500"; barBg = "bg-rose-500"; }
    else if (aqi <= 300) { descriptionKey = "very_unhealthy"; color = "text-fuchsia-500"; barBg = "bg-fuchsia-500"; }
    else if (aqi <= 500) { descriptionKey = "hazardous"; color = "text-red-600"; barBg = "bg-red-600"; }

    const langDict = getSafeProperty(translations, currentLang);
    const desc = langDict ? getSafeProperty(langDict.aqi_descriptions, descriptionKey) : undefined;
    return { description: desc || "Unknown", color: color, barBg: barBg };
}

// Toggle loading spinner
function toggleLoadingSpinner(show) {
    const spinner = document.getElementById('loading-spinner');
    if (show) {
        spinner.classList.remove('hidden');
    } else {
        spinner.classList.add('hidden');
    }
}

// Dashboard Clock Helper
function updateDashboardClock() {
    const clockEl = document.getElementById('dashboard-clock');
    const dateEl = document.getElementById('dashboard-date');
    if (!clockEl || !dateEl) return;

    const now = new Date();

    const hours = String(now.getHours()).padStart(2, '0');
    const minutes = String(now.getMinutes()).padStart(2, '0');
    const seconds = String(now.getSeconds()).padStart(2, '0');
    clockEl.textContent = `${hours}:${minutes}:${seconds}`;

    const options = { weekday: 'long', year: 'numeric', month: 'short', day: 'numeric' };
    const locale = currentLang === 'vi' ? 'vi-VN' : 'en-US';
    dateEl.textContent = now.toLocaleDateString(locale, options);
}

// Retry mechanism for API calls
async function fetchWithRetry(url, retries = 2, delay = 1000) {
    for (let i = 0; i < retries; i++) {
        try {
            const response = await fetch(url);
            if (!response.ok) throw new Error(`HTTP error ${response.status}`);
            return await response.json();
        } catch (error) {
            if (i < retries - 1) await new Promise(resolve => setTimeout(resolve, delay));
            else throw error;
        }
    }
}

// Fetch IP and location data
async function fetchIPInfo() {
    toggleLoadingSpinner(true);
    const langDict = getSafeProperty(translations, currentLang) || {};
    try {
        const data = await fetchWithRetry('https://ipapi.co/json/');
        ipData = data; // Store fetched data
        renderContent();

        // Validate coordinates before fetching weather and air quality
        if (ipData.latitude && ipData.longitude && !isNaN(ipData.latitude) && !isNaN(ipData.longitude)) {
            await Promise.all([
                fetchWeather(ipData.latitude, ipData.longitude),
                fetchAirQuality(ipData.latitude, ipData.longitude)
            ]);
        } else {
            setWeatherError(langDict.invalid_coordinates);
            setAirQualityError(langDict.invalid_coordinates);
        }
    } catch (error) {
        console.error('Error fetching IP info:', error);
        ipData = null;
        renderContent();
        document.getElementById('location').textContent = langDict.unable_to_fetch_location;
        setWeatherError(langDict.weather_data_unavailable);
        setAirQualityError(langDict.air_quality_data_unavailable);
    } finally {
        toggleLoadingSpinner(false);
    }
}

// Set weather fields to error state
function setWeatherError(message) {
    const langDict = getSafeProperty(translations, currentLang) || {};
    document.getElementById('temperature').textContent = langDict.na;
    document.getElementById('feelslike').textContent = langDict.na;
    document.getElementById('condition').textContent = message;
    const canvas = document.getElementById('weather-icon');
    canvas.classList.add('hidden');
    const fallback = document.getElementById('weather-icon-fallback');
    fallback.className = 'wi wi-na text-3xl block text-slate-400';
    fallback.classList.remove('hidden');
    document.getElementById('humidity').textContent = langDict.na;
    document.getElementById('wind_speed').textContent = langDict.na;
    document.getElementById('wind_direction').textContent = langDict.na;
    document.getElementById('uv_index').textContent = langDict.na;
    setWeatherEffect(null); // Fallback to default ambient background
}

// Set air quality fields to error state
function setAirQualityError(message) {
    const langDict = getSafeProperty(translations, currentLang) || {};
    document.getElementById('pm25').textContent = langDict.na;
    document.getElementById('pm10').textContent = langDict.na;
    document.getElementById('us_aqi').textContent = langDict.na;
    document.getElementById('us_aqi_description').textContent = message;
    document.getElementById('us_aqi').className = "text-2xl font-extrabold font-outfit text-slate-500";
    document.getElementById('aqi-progress').style.width = `0%`;
}

// Fetch weather data from Open-Meteo
async function fetchWeather(lat, lon) {
    const langDict = getSafeProperty(translations, currentLang) || {};
    try {
        const response = await fetchWithRetry(`https://api.open-meteo.com/v1/forecast?latitude=${lat}&longitude=${lon}&current=temperature_2m,apparent_temperature,relative_humidity_2m,weather_code,wind_speed_10m,wind_direction_10m,uv_index`);
        weatherData = response; // Store fetched data
        renderContent();
    } catch (error) {
        console.error('Error fetching weather:', error);
        setWeatherError(langDict.weather_data_unavailable);
    }
}

// Fetch air quality data from Open-Meteo
async function fetchAirQuality(lat, lon) {
    const langDict = getSafeProperty(translations, currentLang) || {};
    try {
        const response = await fetchWithRetry(`https://air-quality-api.open-meteo.com/v1/air-quality?latitude=${lat}&longitude=${lon}&current=pm10,pm2_5,us_aqi`);
        airQualityData = response; // Store fetched data
        renderContent();
    } catch (error) {
        console.error('Error fetching air quality:', error);
        setAirQualityError(langDict.air_quality_data_unavailable);
    }
}

